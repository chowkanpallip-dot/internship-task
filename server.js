import path from 'node:path';
import express from 'express';
import session from 'express-session';
import SQLiteStoreFactory from 'connect-sqlite3';
import cors from 'cors';
import helmet from 'helmet';
import { config } from './config/env.js';
import './database/database.js';
import authRoutes from './routes/authRoutes.js';
import { errorHandler, notFoundHandler } from './middleware/errorHandler.js';
const app = express();
const SQLiteStore = SQLiteStoreFactory(session);
app.disable('x-powered-by');
app.use(helmet());
app.use(cors({ origin: config.clientUrl, credentials: true }));
app.use(express.json({ limit: '10kb' }));
app.use(express.urlencoded({ extended: false, limit: '10kb' }));
app.use(session({ store: new SQLiteStore({ db: 'sessions.sqlite3', dir: path.resolve(process.env.DATABASE_DIR || './data') }), secret: config.sessionSecret, resave: false, saveUninitialized: false, cookie: { httpOnly: true, sameSite: 'lax', secure: config.isProduction, maxAge: 1000 * 60 * 60 * 4 } }));
app.get('/api/health', (req, res) => res.json({ status: 'ok' }));
app.use('/api/auth', authRoutes);
app.use(notFoundHandler);
app.use(errorHandler);
app.listen(config.port, () => console.log(`Secure Login API listening on http://localhost:${config.port}`));
export default app;
